package com.zensa.app.auth

import android.content.Context
import android.content.Intent
import android.net.Uri
import android.util.Log
import com.zensa.app.BuildConfig
import kotlinx.coroutines.suspendCancellableCoroutine
import net.openid.appauth.AuthorizationException
import net.openid.appauth.AuthorizationRequest
import net.openid.appauth.AuthorizationResponse
import net.openid.appauth.AuthorizationService
import net.openid.appauth.AuthorizationServiceConfiguration
import net.openid.appauth.ResponseTypeValues
import kotlin.coroutines.resume

/**
 * SsoManager - Single Sign-On with Google using OAuth 2.0 / OpenID Connect.
 *
 * Flow (RFC 8252 "OAuth 2.0 for Native Apps" + RFC 7636 PKCE):
 *   1. [createSignInIntent] builds an Authorization Code request. The AppAuth library
 *      generates a random PKCE code_verifier and sends only its SHA-256 challenge
 *      (code_challenge_method = S256).
 *   2. The user signs in with Google in the system browser (Custom Tab) - Zensa never sees
 *      the Google password.
 *   3. Google redirects back to this app through the reversed-client-id custom scheme.
 *   4. [completeSignIn] exchanges the authorization code + code_verifier for tokens at
 *      Google's token endpoint. No client secret exists or is needed: this is a public
 *      native-app client, which is exactly why PKCE is required.
 *   5. The resulting ID token is sent to the Zensa API (POST /api/auth/google), which
 *      verifies it and issues the Zensa JWT. Tokens are never logged.
 *
 * References: AppAuth for Android (openid.github.io/AppAuth-Android), RFC 8252, RFC 7636,
 * Google "OAuth 2.0 for iOS & Desktop Apps"/Android guidance.
 */
class SsoManager(private val context: Context) {

    private val authService: AuthorizationService by lazy { AuthorizationService(context) }

    /** False until a Google OAuth client id is added to local.properties (see the setup guide). */
    val isConfigured: Boolean
        get() = isClientIdConfigured(BuildConfig.GOOGLE_CLIENT_ID)

    /** Intent to launch with an ActivityResult launcher (opens the Google sign-in page). */
    fun createSignInIntent(): Intent {
        val config = AuthorizationServiceConfiguration(
            Uri.parse(AUTH_ENDPOINT),
            Uri.parse(TOKEN_ENDPOINT)
        )
        val request = AuthorizationRequest.Builder(
            config,
            BuildConfig.GOOGLE_CLIENT_ID,
            ResponseTypeValues.CODE,
            redirectUri(BuildConfig.GOOGLE_REDIRECT_SCHEME)
        )
            .setScope("openid email profile")
            .build() // PKCE (code_verifier + S256 challenge) is generated by default
        return authService.getAuthorizationRequestIntent(request)
    }

    /** Handles the browser redirect result and performs the code-for-token exchange. */
    suspend fun completeSignIn(data: Intent?): SsoOutcome {
        if (data == null) return SsoOutcome.Cancelled // user pressed Back / closed the browser

        val response = AuthorizationResponse.fromIntent(data)
        val exception = AuthorizationException.fromIntent(data)

        if (response == null) {
            return if (exception != null && isUserCancellation(exception)) {
                SsoOutcome.Cancelled
            } else {
                Log.w(TAG, "Authorization failed (code=${exception?.code})")
                SsoOutcome.Failed("Sign-in failed")
            }
        }

        return suspendCancellableCoroutine { cont ->
            authService.performTokenRequest(response.createTokenExchangeRequest()) { tokenResponse, ex ->
                val idToken = tokenResponse?.idToken
                val outcome = when {
                    idToken != null -> SsoOutcome.IdToken(idToken)
                    ex != null && isUserCancellation(ex) -> SsoOutcome.Cancelled
                    else -> {
                        Log.w(TAG, "Token exchange failed (code=${ex?.code})")
                        SsoOutcome.Failed("Sign-in failed")
                    }
                }
                if (cont.isActive) cont.resume(outcome)
            }
        }
    }

    private fun isUserCancellation(ex: AuthorizationException): Boolean =
        ex.type == AuthorizationException.TYPE_GENERAL_ERROR &&
            ex.code == AuthorizationException.GeneralErrors.USER_CANCELED_AUTH_FLOW.code

    companion object {
        private const val TAG = "SsoManager"
        const val AUTH_ENDPOINT = "https://accounts.google.com/o/oauth2/v2/auth"
        const val TOKEN_ENDPOINT = "https://oauth2.googleapis.com/token"
        const val REDIRECT_PATH = "/oauth2redirect"

        /** A real Google client id looks like "1234-abc.apps.googleusercontent.com". */
        fun isClientIdConfigured(clientId: String): Boolean =
            clientId.endsWith(".apps.googleusercontent.com") &&
                clientId.removeSuffix(".apps.googleusercontent.com").isNotBlank()

        /** Redirect URI Google expects for native apps: "<reversed client id>:/oauth2redirect". */
        fun redirectUri(scheme: String): Uri = Uri.parse("$scheme:$REDIRECT_PATH")
    }
}

/** Result of one sign-in attempt. */
sealed class SsoOutcome {
    /** Success. The token is deliberately hidden from toString() so it can never reach a log. */
    class IdToken(val value: String) : SsoOutcome() {
        override fun toString(): String = "IdToken(***)"
    }

    /** The user closed the browser / pressed Back. Not an error. */
    data object Cancelled : SsoOutcome()

    /** Something went wrong (network, rejected code, ...). [reason] is safe to show. */
    data class Failed(val reason: String) : SsoOutcome()

    /** No Google client id has been configured in this build. */
    data object NotConfigured : SsoOutcome()
}
